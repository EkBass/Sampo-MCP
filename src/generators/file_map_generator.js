// <block: core>
export async function mapFiles(inputDirs, options = {}) {
    const mode = options.mode ?? "module";
    const output = makeOutputSkeleton();
    const filesMap = output.files;
    const dupes = new Map(); // basename -> [paths]

    try {
        // Always include this script's own parent directory (src) - RECURSIVE
        const scanDirs = [path.dirname(__dirname)];

        // Add user-specified dirs (as given), also RECURSIVE
        const extra = (inputDirs ?? []).map((d) => path.resolve(process.cwd(), d));
        scanDirs.push(...extra);

        // Validate dirs
        for (const dir of scanDirs) {
            const stat = await fs.stat(dir).catch(() => null);
            if (!stat || !stat.isDirectory()) {
                throw new Error(`Not a directory: ${dir}`);
            }
        }

        // Collect recursive files
        const allFiles = [];
        for (const dir of scanDirs) {
            const top = await listRecursiveJs(dir); 
            allFiles.push(...top);
        }

        // Build mapping with duplicate detection
        for (const f of allFiles) {
            const key = baseNoExt(f);
            const rel = relFromCwd(f);
            if (Object.prototype.hasOwnProperty.call(filesMap, key)) {
                const prev = filesMap[key];
                if (!dupes.has(key)) dupes.set(key, [prev]);
                dupes.get(key).push(rel);
            } else {
                filesMap[key] = rel;
            }
        }

        if (dupes.size > 0) {
            output.metadata.errors = true;
            const msgs = [];
            for (const [k, arr] of dupes.entries()) {
                msgs.push(`Duplicate basename "${k}" detected in: ${arr.join(", ")}`);
            }
            output.metadata.error_message = msgs.join(" | ");
        }

        if (options.save) {
            const outDir = mode === "module"
                ? path.join(path.dirname(__dirname), "..", "data")
                : path.join(process.cwd(), "data");
            const outFile = path.join(outDir, "file_tree.yaml");
            await writeYaml(outFile, output);
            output.metadata.output_file = toForwardSlash(outFile);
        }
        
        // Generate file_paths.js if requested
        if (options.generatePaths) {
            const pathsFile = await generateFilePathsModule(filesMap);
            output.metadata.paths_file = toForwardSlash(pathsFile);
        }
    } catch (err) {
        output.metadata.errors = true;
        output.metadata.error_message = String(err?.message ?? err);
    }

    return output;
}
// </block: core>


// <block: cli>
async function runCli() {
    const args = process.argv.slice(2); // additional dirs to include (recursive)
    const result = await mapFiles(args, { 
        save: true, 
        generatePaths: false,  // Don't generate file_paths.js (deprecated)
        mode: "cli" 
    });
    
    // Output YAML to stderr instead of stdout to avoid polluting MCP JSON stream
    const yamlOutput = generateYamlFromData(result);
    process.stderr.write(yamlOutput + "\n");
    
    if (result.metadata.errors) process.exitCode = 2;
}

const isDirectRun = import.meta.url === pathToFileURL(process.argv[1])?.href;
if (isDirectRun) runCli();
// </block: cli>


// <block: generate_file_paths>
export async function generateFilePathsModule(filesMap) {
    const srcDir = path.dirname(__dirname);
    const outFile = path.join(srcDir, "file_paths.js");
    
    const lines = [];
    lines.push("// <file_info: file_paths.js>");
    lines.push("/*");
    lines.push("- Project: Sampo-MCP");
    lines.push("- File: src/file_paths.js");
    lines.push("- Auto-generated centralized path constants");
    lines.push("- DO NOT EDIT MANUALLY - regenerate with: node src/generators/file_map_generator.js");
    lines.push("- Generated: " + fmtISO_DDMMYYYYTHHMMSS());
    lines.push("- Usage: import { LOGGER } from './file_paths.js'; then import X from LOGGER;");
    lines.push("*/");
    lines.push("// </file_info: file_paths.js>");
    lines.push("");
	lines.push("// <block: imports/>");
	lines.push("");
    lines.push("// <block: path_mappings>");
    lines.push("// Path constants for centralized import management");
    lines.push("// When a file moves, update ONLY here - all imports stay valid");
    lines.push("");
    
    // Sort keys and group by directory for readability
    const sortedKeys = Object.keys(filesMap).sort();
    const byDir = new Map();
    
    for (const key of sortedKeys) {
        const relPath = filesMap[key];
        const fromSrc = relPath.replace(/^\.\/src\//, "./");
        const dir = path.dirname(fromSrc);
        
        if (!byDir.has(dir)) byDir.set(dir, []);
        byDir.get(dir).push({ key, path: fromSrc });
    }
    
    // Generate named exports grouped by directory
    for (const [dir, files] of byDir) {
        const dirName = dir === "." ? "Core modules" : dir.replace("./", "").replace(/\//g, " / ");
        lines.push(`// ${dirName}`);
        
        for (const { key, path: filePath } of files) {
            const constName = key.toUpperCase();
            lines.push(`export const ${constName} = "${filePath}";`);
        }
        lines.push("");
    }
    
    // Generate _PATHS object for dynamic lookups
    lines.push("// Object map for dynamic lookups (when you can't use import)");
    lines.push("export const _PATHS = {");
    
    for (const key of sortedKeys) {
        const constName = key.toUpperCase();
        lines.push(`    ${key}: ${constName},`);
    }
    
    lines.push("};");
    lines.push("// </block: path_mappings>");
    lines.push("");
    
    await fs.writeFile(outFile, lines.join("\n"), "utf-8");
    return outFile;
}
