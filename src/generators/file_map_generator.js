// <block: imports>
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
// </block: imports>


// <block: helpers>
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function toForwardSlash(p) {
    return p.replace(/\\/g, "/");
}

function ensureDotSlash(p) {
    const fwd = toForwardSlash(p);
    return fwd.startsWith("./") ? fwd : `./${fwd}`;
}

function fmtISO_DDMMYYYYTHHMMSS(date = new Date()) {
    const pad = (n) => String(n).padStart(2, "0");
    const dd = pad(date.getDate());
    const mm = pad(date.getMonth() + 1);
    const yyyy = date.getFullYear();
    const HH = pad(date.getHours());
    const MM = pad(date.getMinutes());
    const SS = pad(date.getSeconds());
    return `${dd}.${mm}.${yyyy}T${HH}:${MM}:${SS}`;
}

function makeOutputSkeleton() {
    return {
        metadata: {
            timestamp: fmtISO_DDMMYYYYTHHMMSS(),
            description: "Autogenerated file mapping.",
            errors: false,
            error_message: null
        },
        files: {}
    };
}

function relFromCwd(fileAbs) {
    const rel = path.relative(process.cwd(), fileAbs);
    return ensureDotSlash(rel);
}

function baseNoExt(fileAbs) {
    return path.basename(fileAbs, path.extname(fileAbs));
}

async function writeYaml(filePath, dataObj) {
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    const yamlContent = generateYamlFromData(dataObj);
    await fs.writeFile(filePath, yamlContent, "utf-8");
    return filePath;
}

// Ignore patterns for directory scanning
function shouldIgnoreDir(dirName) {
    return dirName.startsWith(".") || dirName === "sandbox" || dirName === "node_modules";
}

// Recursive listing with ignore rules
async function listRecursiveJs(dirAbs) {
    const out = [];
    const entries = await fs.readdir(dirAbs, { withFileTypes: true });
    for (const e of entries) {
        const fullPath = path.join(dirAbs, e.name);

        if (e.isFile() && [".js", ".txt", ".md"].includes(path.extname(e.name).toLowerCase())) {
            out.push(fullPath);
        } 
        else if (e.isDirectory() && !shouldIgnoreDir(e.name)) {
            const subFiles = await listRecursiveJs(fullPath);
            out.push(...subFiles);
        }
    }
    return out;
}

// Generate YAML from data object
function generateYamlFromData(data) {
    const lines = [];
    
    lines.push("# FILE MAPPING");
    lines.push(`# Generated: ${data.metadata.timestamp}`);
    lines.push("");
    
    lines.push("# METADATA");
    lines.push("metadata:");
    lines.push(`  timestamp: "${data.metadata.timestamp}"`);
    lines.push(`  description: "${data.metadata.description}"`);
    lines.push(`  errors: ${data.metadata.errors}`);
    if (data.metadata.error_message) {
        lines.push(`  error_message: "${data.metadata.error_message}"`);
    } else {
        lines.push("  error_message: null");
    }
    if (data.metadata.output_file) {
        lines.push(`  output_file: "${data.metadata.output_file}"`);
    }
    lines.push("");
    
    lines.push("# FILES");
    lines.push("files:");
    
    const sortedKeys = Object.keys(data.files).sort();
    for (const key of sortedKeys) {
        lines.push(`  ${key}: "${data.files[key]}"`);
    }
    
    lines.push("");
    lines.push("# END");
    
    return lines.join("\n");
}
